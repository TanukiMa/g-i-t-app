"""The time budget of one pipeline run: a run must never hang on the AI.

Every request has a time limit, every summary a total limit (summarize.py), and the whole run a budget: no new site is
fetched in the last FETCH_RESERVE_MIN minutes and no new summary is started in the last SUMMARY_RESERVE_MIN. What is not
summarized in time is stored as SUMMARY_FAILED and regenerated by a later run.

STALK_BUDGET_MIN is read when a deadline is asked for, so a tool may set it before it starts (resummarize.py,
recover_rebaselined.py); the clock starts when this module is first imported.
"""
import os
import time

START = time.monotonic()
SUMMARY_RESERVE_MIN = 8      # no new summary is started in the last minutes (push and dashboard need them)
FETCH_RESERVE_MIN = 12       # no new site is fetched in the last minutes


def budget_min() -> float:
    return float(os.environ.get("STALK_BUDGET_MIN") or 40)      # whole run (the workflow limit is 60 min)


def run_deadline(reserve_min: float) -> float:
    """Monotonic time after which nothing new should be started (the run budget minus a reserve)."""
    return START + (budget_min() - reserve_min) * 60
